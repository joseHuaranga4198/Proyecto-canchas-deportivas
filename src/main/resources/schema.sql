CREATE TABLE IF NOT EXISTS usuario (
    id_usuario BIGINT AUTO_INCREMENT PRIMARY KEY,
    nombres VARCHAR(100) NOT NULL,
    apellidos VARCHAR(100) NOT NULL,
    documento VARCHAR(20) NOT NULL UNIQUE,
    telefono VARCHAR(20),
    correo VARCHAR(100) NOT NULL UNIQUE,
    contrasena VARCHAR(255) NOT NULL,
    rol VARCHAR(20) NOT NULL,
    estado VARCHAR(20) NOT NULL
);

CREATE TABLE IF NOT EXISTS categoria (
    id_categoria BIGINT AUTO_INCREMENT PRIMARY KEY,
    nombre VARCHAR(50) NOT NULL UNIQUE,
    descripcion VARCHAR(255),
    estado VARCHAR(20) NOT NULL
);

CREATE TABLE IF NOT EXISTS cancha (
    id_cancha BIGINT AUTO_INCREMENT PRIMARY KEY,
    id_categoria BIGINT NOT NULL,
    nombre VARCHAR(100) NOT NULL,
    caracteristicas VARCHAR(500),
    precio_hora DECIMAL(10,2) NOT NULL,
    estado VARCHAR(20) NOT NULL,
    CONSTRAINT fk_cancha_categoria FOREIGN KEY (id_categoria) REFERENCES categoria(id_categoria)
);

CREATE TABLE IF NOT EXISTS reserva (
    id_reserva BIGINT AUTO_INCREMENT PRIMARY KEY,
    id_usuario BIGINT NOT NULL,
    id_cancha BIGINT NOT NULL,
    fecha DATE NOT NULL,
    hora_inicio TIME NOT NULL,
    hora_fin TIME NOT NULL,
    importe DECIMAL(10,2) NOT NULL,
    estado VARCHAR(20) NOT NULL,
    fecha_registro TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_reserva_usuario FOREIGN KEY (id_usuario) REFERENCES usuario(id_usuario),
    CONSTRAINT fk_reserva_cancha FOREIGN KEY (id_cancha) REFERENCES cancha(id_cancha)
);

CREATE TABLE IF NOT EXISTS pago (
    id_pago BIGINT AUTO_INCREMENT PRIMARY KEY,
    id_reserva BIGINT NOT NULL UNIQUE,
    importe DECIMAL(10,2) NOT NULL,
    fecha_pago TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    estado VARCHAR(20) NOT NULL,
    CONSTRAINT fk_pago_reserva FOREIGN KEY (id_reserva) REFERENCES reserva(id_reserva)
);

CREATE TABLE IF NOT EXISTS bloqueo_cancha (
 id_bloqueo BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_cancha BIGINT NOT NULL REFERENCES cancha(id_cancha),
 fecha DATE NOT NULL, hora_inicio TIME NOT NULL, hora_fin TIME NOT NULL,
 motivo VARCHAR(250) NOT NULL, estado VARCHAR(20) NOT NULL DEFAULT 'ACTIVO',
 id_administrador BIGINT NOT NULL REFERENCES usuario(id_usuario),
 fecha_registro TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CHECK(hora_fin > hora_inicio), CHECK(estado IN ('ACTIVO','ANULADO'))
);
CREATE TABLE IF NOT EXISTS devolucion (
 id_devolucion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_pago BIGINT NOT NULL UNIQUE REFERENCES pago(id_pago),
 importe DECIMAL(10,2) NOT NULL CHECK(importe > 0),
 fecha_devolucion TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 motivo VARCHAR(250) NOT NULL,
 id_usuario BIGINT NOT NULL REFERENCES usuario(id_usuario)
);
CREATE INDEX IF NOT EXISTS idx_reserva_horario ON reserva(id_cancha,fecha,estado,hora_inicio,hora_fin);
CREATE INDEX IF NOT EXISTS idx_reserva_usuario ON reserva(id_usuario,fecha);
CREATE INDEX IF NOT EXISTS idx_bloqueo_horario ON bloqueo_cancha(id_cancha,fecha,estado);

UPDATE usuario SET estado = 'SUSPENDIDO' WHERE estado = 'BLOQUEADO';
